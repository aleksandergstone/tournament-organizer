export function isSailingFormat(format: string): boolean {
  return [
    'fleet-racing',
    'match-racing',
    'team-racing',
    'round-robin',
    'knockout',
    'group-stage-finals',
    'flighted-racing',
    'medal-race',
    'custom-regatta',
  ].includes(format);
}

export function sailingModeOf(format: string): SailingModeInfo | undefined {
  return SAILING_MODES.find(m => m.format === format);
}

export function visibleSailingGroups(format: string): readonly SettingGroup[] {
  const mode = sailingModeOf(format);
  return mode ? mode.settings : [];
}
