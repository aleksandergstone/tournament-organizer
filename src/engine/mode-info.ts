function buildSpec(m: ModeInfo): ModeSpec {
  const cls = CLASS_OF[m.format];
  const roles = ROLES[cls];
  const groups = ALL_GROUPS.filter(g => (m.settings as readonly SettingGroup[]).includes(g));
  const fields: FieldRule[] = [];
  for (const g of groups) {
    for (const f of SETTING_FIELDS[g]) {
      const role = roles[f];
      // No role means the field is not applicable to this mode: it is never
      // rendered, not greyed out and not hidden behind "advanced".
      if (!role || fields.some(x => x.field === f)) continue;
      // Two statuses override the shared sentence, because the shared one is
      // written for the mode where the setting actually does the work.
      const why = role.status === 'reporting' ? 'mode.why.reporting'
        : (role.affects === 'none' && role.status === 'advanced') ? 'mode.why.inert'
          : WHY[f];
      fields.push({ field: f, group: g, status: role.status, affects: role.affects, why });
    }
  }
  return {
    format: m.format,
    info: m,
    groups,
    fields,
    stages: STAGES[m.format],
    points: POINTS_STMT[cls],
    draws: DRAW_STMT[cls],
    groupSize: GROUP_SIZE_STMT[cls],
    advancement: ADVANCE_STMT[cls],
    tiebreak: TIEBREAK_STMT[cls],
    reporting: REPORTING_STMT[cls],
    edgeCases: EDGE_CASES[cls],
    unsupported: UNSUPPORTED[cls],
    structure: { contains: CONTAINS[cls], excludes: EXCLUDES[cls] },
  };
}

