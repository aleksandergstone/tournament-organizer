// What each tournament mode means, which settings it actually needs, and what
// the app will generate for a given field size.
//
// This is the single source of truth behind the setup screens: the mode picker,
// the explanations, the presets, the visible settings and the preview all read
// from here, so a format can never be described one way and generated another.
// Pure and deterministic — no DOM, no randomness, no tournament state.
