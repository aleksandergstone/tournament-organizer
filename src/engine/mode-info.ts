// ---- what the app will generate --------------------------------------------

export interface PreviewRow { key: keyof Dict; value: string }

export interface StructurePreview {
  format: CompetitionFormat;
  /** Which kind of output the organizer gets. */
  kind: 'bracket' | 'table' | 'groups' | 'rounds' | 'fixtures';
  titleKey: keyof Dict;
  rows: PreviewRow[];
  notes: (keyof Dict)[];
  /** Matches that exist as soon as the organizer presses generate. */
  matches: number | null;
  /** Matches that only appear later — the next Swiss round, the knockout. */
  later: number;
  /** Free passes the plan contains. A bye is a slot, not a match to play. */
  byes: number;
  /** The field size the numbers were computed for. */
  count: number;
  /** True when the numbers come from a sample, not a real participant count. */
  assumed: boolean;
}

/** Field size used for the preview when the organizer has not said. */
export const PREVIEW_SAMPLE = 8;

function pow2(n: number): number {
  let r = 1;
  while (r < n) r *= 2;
  return r;
}
const choose2 = (n: number) => (n * (n - 1)) / 2;

/** Rounds a round robin needs: one per opponent, plus one when someone sits out. */
function rrRounds(n: number): number {
  return n % 2 === 1 ? n : n - 1;
}

function syntheticField(count: number): Participant[] {
  return Array.from({ length: count }, (_, i) => ({
    id: `preview_${i}`,
    name: `P${i + 1}`,
    kind: 'player' as const,
    active: true,
    seed: i + 1,
    tags: [],
  }));
}

/**
 * What the real generator would create for a field of this size — counted, not
 * estimated, by running it on a synthetic field. Seeding is forced to the input
 * order so the count is deterministic; the order of the pairings never changes
 * how many matches there are.
 *
 * Byes are counted apart: the app stores a free pass as a match row, but nobody
 * plays it, and a preview that counted it would overstate the work.
 */
function planned(format: string, count: number, rules: RuleSet): { played: number; byes: number } {
  const ps = syntheticField(count);
  const r: RuleSet = { ...rules, seeding: 'seeded' };
  const all: Match[] =
    format === 'single-elimination' ? genSingleElim(ps, r).matches
      : format === 'double-elimination' ? genDoubleElim(ps, r).matches
        : format === 'league' ? genLeague(ps, r)
          : format === 'groups-knockout' ? genGroupsKnockout(ps, r).matches
            : format === 'swiss' ? swissPairings(ps, [], new Map(ps.map(p => [p.id, 0])), 1)
              : genRoundRobin(ps, r);
  // A free pass is a row with one participant and no opponent. A row with two
  // empty slots is not a bye at all — it is a later round waiting for a result,
  // and it still belongs to the total the organizer will play.
  const byes = all.filter(m => (m.homeId === null) !== (m.awayId === null)).length;
  return { played: all.length - byes, byes };
}

/**
 * Describes the output for a format at a given field size, so the setup screens
 * can show it live and tests can hold it against the generators.
 */
export function previewStructure(
  format: string,
  participantCount: number | null | undefined,
  rules: RuleSet,
): StructurePreview {
  const mode = modeOf(format);
  const real = typeof participantCount === 'number' && participantCount >= 2;
  const count = real ? Math.floor(participantCount) : PREVIEW_SAMPLE;
  const rows: PreviewRow[] = [];
  const notes: (keyof Dict)[] = [];
  let kind: StructurePreview['kind'] = 'bracket';
  let matches: number | null = null;
  let later = 0;
  let byes = 0;
  const push = (key: keyof Dict, value: string | number) => rows.push({ key, value: String(value) });
  const byeRows = () => { if (byes > 0) push('preview.byes', byes); };

  switch (format) {
    case 'single-elimination': {
      const size = pow2(count);
      ({ played: matches, byes } = planned(format, count, rules));
      push('preview.rounds', Math.log2(size));
      push('preview.matches', matches);
      byeRows();
      if (size > count) notes.push('preview.noteByes');
      push('preview.ends', t('preview.endsFinal'));
      break;
    }
    case 'double-elimination': {
      ({ played: matches, byes } = planned(format, count, rules));
      push('preview.winnersLosers', t('preview.wlCount', { n: Math.max(0, matches - 1) }));
      push('preview.grandFinal', 1);
      push('preview.matches', matches);
      byeRows();
      notes.push('preview.noteReset');
      break;
    }
    case 'round-robin':
    case 'team-match':
    case 'individual-match':
    case 'custom': {
      kind = format === 'custom' ? 'fixtures' : 'table';
      ({ played: matches, byes } = planned(format, count, rules));
      push('preview.rounds', rrRounds(count));
      push('preview.matches', matches);
      byeRows();
      if (byes > 0) notes.push('preview.noteRRBye');
      push('preview.meetings', rules.homeAway ? t('preview.twice') : t('preview.once'));
      push('preview.ends', t('preview.endsTable'));
      if (format === 'custom') notes.push('preview.noteCustom');
      break;
    }
    case 'league': {
      kind = 'table';
      ({ played: matches, byes } = planned(format, count, rules));
      const double = rules.homeAway ?? true;
      push('preview.matchdays', rrRounds(count) * (double ? 2 : 1));
      push('preview.matches', matches);
      byeRows();
      if (byes > 0) notes.push('preview.noteRRBye');
      push('preview.meetings', double ? t('preview.twice') : t('preview.once'));
      push('preview.ends', t('preview.endsTable'));
      break;
    }
    case 'swiss': {
      // Only the first round exists after generating; the rest are paired from
      // the standings, round by round, as results come in.
      kind = 'rounds';
      const plannedRounds = Math.max(1, rules.swissRounds ?? 5);
      const first = planned(format, count, rules);
      matches = first.played;
      byes = first.byes;
      const perRound = first.played + first.byes;
      later = (plannedRounds - 1) * perRound;
      push('preview.roundsPlanned', plannedRounds);
      push('preview.matchesPerRound', perRound);
      push('preview.matchesTotal', perRound * plannedRounds);
      notes.push('preview.noteSwiss');
      if (byes > 0) notes.push('preview.noteSwissBye');
      break;
    }
    case 'groups-knockout': {
      // The group stage is generated now; the bracket is built from the
      // qualifiers once the groups are finished.
      kind = 'groups';
      const plan = groupPlan(rules, count);
      ({ played: matches, byes } = planned(format, count, rules));
      push('preview.groups', plan.groups);
      push('preview.groupSizes', plan.sizes.join(' / '));
      push('preview.groupMatches', matches);
      byeRows();
      push('preview.qualifiers', plan.qualifiers);
      later = Math.max(0, plan.qualifiers - 1);
      push('preview.koMatches', later);
      if (plan.knockoutByes > 0) push('preview.koByes', plan.knockoutByes);
      if (plan.uneven) notes.push('preview.noteUnevenGroups');
      notes.push('preview.noteGroupsKo');
      break;
    }
    default:
      kind = 'bracket';
  }

  return {
    format: mode.format,
    kind,
    titleKey: mode.points && !mode.bracket ? 'preview.titleTable' : 'preview.titleStructure',
    rows,
    notes,
    matches,
    later,
    byes,
    count,
    assumed: !real,
  };
}

// ---- the plan: stages, flow and what stays manual --------------------------

export interface StagePlan {
  key: keyof Dict;
  produces: keyof Dict;
  flow: keyof Dict;
  /** False for a stage the organizer has to run, or the engine, not the app. */
  generatedNow: boolean;
  /** What this stage costs in matches at the given field size, when known. */
  matches: number | null;
}

/**
 * The stages this format runs, with the ones the app builds now marked against
 * the ones the organizer runs later. Swiss is the clearest case: round 1 is
 * generated, every later round is paired from the standings after results come
 * in, and a group stage is generated while the knockout waits for qualifiers.
 */
export function stagePlan(
  format: string,
  rules: RuleSet,
  participantCount?: number | null,
): StagePlan[] {
  const spec = specFor(format);
  const p = previewStructure(format, participantCount, rules);
  const real = typeof participantCount === 'number' && participantCount >= 2;
  const plannedRounds = Math.max(1, rules.swissRounds ?? 5);
  return spec.stages.map((s, i) => {
    let matches: number | null = null;
    let generatedNow = true;
    if (format === 'swiss') {
      generatedNow = i === 0;
      matches = i === 0 ? p.matches : (plannedRounds > 1 ? Math.floor(((p.matches ?? 0) + p.byes)) : 0);
    } else if (format === 'groups-knockout') {
      generatedNow = i === 0;
      matches = i === 0 ? p.matches : p.later;
    } else if (format === 'double-elimination') {
      // The grand final is one match, and it exists from the start.
      matches = i === 2 ? 1 : null;
    } else {
      matches = i === 0 ? p.matches : null;
    }
    if (!real && format === 'swiss' && i > 0) matches = null;
    return { key: s.key, produces: s.produces, flow: s.flow, generatedNow, matches };
  });
}

/** What the organizer still has to do by hand in this format. */
export function manualSteps(format: string): (keyof Dict)[] {
  switch (format) {
    case 'swiss': return ['mode.manual.nextRound', 'mode.manual.byeEntry'];
    case 'groups-knockout': return ['mode.manual.qualifiers', 'mode.manual.knockout'];
    case 'double-elimination': return ['mode.manual.deadMatch'];
    case 'custom': return ['mode.manual.customStages'];
    case 'single-elimination': return ['mode.manual.deadMatch'];
    default: return ['mode.manual.venues'];
  }
}

/**
 * True when the plan cannot be counted yet: fewer than two participants, or a
 * field size the mode cannot take. The screens warn about it before creation
 * rather than saving a tournament nobody can generate.
 */
export function previewWarning(
  format: string,
  rules: RuleSet,
  participantCount?: number | null,
): keyof Dict | null {
  const n = typeof participantCount === 'number' ? Math.floor(participantCount) : null;
  if (n === null) return null;                     // a sample is shown and labelled
  if (n < 2) return 'mode.warn.tooFew';
  if (format === 'groups-knockout') {
    const groups = Math.max(2, Math.floor(rules.groupCount ?? 2));
    if (n < groups * 2) return 'mode.warn.groupSize';
  }
  if (format === 'swiss' && n < 3) return 'mode.warn.tooFew';
  if (format === 'league' && n < 3) return 'mode.warn.leagueTooFew';
  return null;
}

// ---- does this combination of rules make sense? ----------------------------

/**
 * Rule combinations that are legal but almost certainly not what the organizer
 * meant, plus the combinations the mode rules forbid outright.
 *
 * The same shape the engine's validation uses, so the setup screens and
 * `validateTournament` share it. Pure: it only reads rules and field size.
 */
export function validateModeSetup(
  format: string,
  rules: RuleSet,
  participantCount?: number | null,
): ValidationIssueLike[] {
  const issues: ValidationIssueLike[] = [];
  const n = typeof participantCount === 'number' && participantCount >= 2
    ? Math.floor(participantCount)
    : null;
  const spec = specFor(format);

  // --- points, in every mode -------------------------------------------------
  if (showsField(format, 'winPoints')) {
    const pts = [rules.winPoints, rules.drawPoints, rules.lossPoints, rules.walkoverWinnerPoints];
    if (pts.some(p => !Number.isFinite(p) || p < 0)) {
      issues.push({ field: 'winPoints', message: t('mode.err.negativePoints') });
    }
  }

  // --- draws, in every mode --------------------------------------------------
  if (spec.draws.policy === 'requires-resolution' && rules.allowDraws) {
    // A level match cannot advance anybody, so the organizer has to say what
    // settles it. Without a rule the app refuses the result, so we say so here
    // instead of letting them find out at match time.
    if ((rules.drawResolution ?? 'none') === 'none') {
      issues.push({ field: 'drawResolution', message: t('mode.err.drawNeedsRule') });
    } else if (rules.drawResolution === 'overtime' && !rules.overtimeAllowed) {
      issues.push({ field: 'overtimeAllowed', message: t('mode.err.overtimeNeeded') });
    }
  }

  // --- tie-breaks, where a table decides the order ----------------------------
  if (showsField(format, 'tiebreakOrder') && rules.tiebreakOrder.length === 0) {
    issues.push({ field: 'tiebreakOrder', message: t('mode.err.noTiebreak') });
  }

  if (format === 'groups-knockout') {
    const plan = groupPlan(rules, n);
    if ((rules.groupCount ?? 2) < 2) issues.push({ field: 'groupCount', message: t('mode.err.groupsMin') });
    if ((rules.advancePerGroup ?? 2) < 1) issues.push({ field: 'advancePerGroup', message: t('mode.err.advanceMin') });
    if (n) {
      const groups = Math.max(2, Math.floor(rules.groupCount ?? 2));
      const advance = Math.max(1, Math.floor(rules.advancePerGroup ?? 2));
      if (groups > n || plan.smallest < 2) {
        issues.push({ field: 'groupCount', message: t('mode.err.groupsTooMany', { groups, n }) });
      }
      // Someone has to stay behind in each group, or the group stage decides
      // nothing and the bracket is not a qualification at all.
      if (advance >= plan.smallest) {
        issues.push({ field: 'advancePerGroup', message: t('mode.err.advanceTooMany', { advance, perGroup: plan.smallest }) });
      }
      if (groups * advance < 2) {
        issues.push({ field: 'advancePerGroup', message: t('mode.err.advanceNoBracket') });
      }
    }
  }

  if (format === 'swiss') {
    const rounds = rules.swissRounds ?? 5;
    if (rounds < 1) issues.push({ field: 'swissRounds', message: t('mode.err.roundsMin') });
    if (n && rounds > n - 1) {
      issues.push({ field: 'swissRounds', message: t('mode.err.roundsTooMany', { rounds, max: n - 1 }) });
    }
  }

  // Settings the mode shows but the generator cannot act on are named in the
  // settings panel and in the mode explanation. They are deliberately NOT an
  // issue here: Custom always has some, so an issue would make a custom event
  // impossible to create.

  // --- a custom event has to state its stage ----------------------------------
  // The one thing a custom format may not leave to the app: what it is built
  // from. An ungenerated stage is refused by name rather than quietly ignored.
  if (format === 'custom') {
    const stage = rules.customStage;
    if (!stage) {
      issues.push({ field: 'customStage', message: t('mode.err.stageRequired') });
    } else if (!GENERATED_CUSTOM_STAGES.includes(stage)) {
      issues.push({ field: 'customStage', message: t('mode.err.stageNotBuilt', { stage: t(`mode.stageName.${stage}` as never) }) });
    }
  }
  if ((format === 'round-robin' || format === 'team-match' || format === 'individual-match')
      && n && choose2(n) * (rules.homeAway ? 2 : 1) > 400) {
    issues.push({ field: 'homeAway', message: t('mode.err.tooManyMatches', { n }) });
  }

  if (format === 'league' && n && n < 3) {
    issues.push({ field: 'format', message: t('mode.err.leagueTooSmall', { n }) });
  }

  return issues;
}

