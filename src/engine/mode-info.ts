// ---- group sizes -----------------------------------------------------------

export interface GroupPlan {
  groups: number;
  /** Participants per group, biggest first as produced by the remainder split. */
  sizes: number[];
  smallest: number;
  largest: number;
  /** True when the count does not divide evenly — allowed, and explained. */
  uneven: boolean;
  qualifiers: number;
  knockoutSize: number;
  knockoutByes: number;
}

/**
 * How the field is dealt into groups and what that leaves for the knockout.
 *
 * Sizes come out as even as the count allows: the remainder is spread one
 * participant at a time, so a field of 10 in 4 groups becomes 3/3/2/2 rather
 * than 4/2/2/2. The generator deals participants in blocks, which also spreads
 * the strong and the weak across different groups. Uneven groups are a normal
 * outcome, not a mistake, and the screen says so instead of hiding the number.
 */
export function groupPlan(rules: RuleSet, participantCount?: number | null): GroupPlan {
  const real = typeof participantCount === 'number' && participantCount >= 2;
  const count = real ? Math.floor(participantCount) : PREVIEW_SAMPLE;
  const groups = Math.max(2, Math.floor(rules.groupCount ?? 2));
  const advance = Math.max(1, Math.floor(rules.advancePerGroup ?? 2));
  const base = Math.floor(count / groups);
  const extra = count % groups;
  const sizes = Array.from({ length: groups }, (_, i) => base + (i < extra ? 1 : 0));
  const qualifiers = groups * advance;
  const knockoutSize = pow2(qualifiers);
  return {
    groups,
    sizes,
    smallest: sizes.length ? Math.min(...sizes) : 0,
    largest: sizes.length ? Math.max(...sizes) : 0,
    uneven: extra > 0,
    qualifiers,
    knockoutSize,
    knockoutByes: Math.max(0, knockoutSize - qualifiers),
  };
}

