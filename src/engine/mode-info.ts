export type SettingGroup =
  | 'scoring'      // points per result
  | 'tiebreak'     // how equal points are separated
  | 'seeding'      // who plays whom in the first round
  | 'groups'       // group count and who advances
  | 'rounds'       // how many Swiss rounds
  | 'meeting'      // home & away
  | 'byes';        // free pass points for an odd field

export interface ModeInfo {
  format: CompetitionFormat;
  /** Where the mode lives in the picker — by intent, not by feature name. */
  group: 'quick' | 'ranking' | 'groups' | 'other';
  /** One-line meaning, plain language, no jargon. */
  meaning: keyof Dict;
  /** A concrete, checkable example: "8 players → …". */
  example: keyof Dict;
  goodFor: keyof Dict;
  notIncluded: keyof Dict;
  /** Setting groups this mode genuinely needs; anything else is not shown. */
  settings: readonly SettingGroup[];
  /** Points are part of the result here (a table is produced). */
  points: boolean;
  /** The event ends in a knockout bracket. */
  bracket: boolean;
  /** The whole fixture list is generated in one go. */
  autoGenerated: boolean;
}

