export interface SummaryLine { key: keyof Dict; value: string }

/**
 * The rules that actually apply, as short lines — the "before you create it"
 * block. Only visible groups produce a line, so a bracket never claims to score
 * points and a league never claims to have rounds.
 */
export function summaryRows(
  format: string,
  rules: RuleSet,
  participantCount?: number | null,
): SummaryLine[] {
  const rows: SummaryLine[] = [];
  const spec = specFor(format);
  const has = (g: SettingGroup) => visibleGroups(format).includes(g);
  const resolution = rules.drawResolution ?? 'none';

  // The one line that says what this format actually is.
  rows.push({ key: 'mode.sum.advances', value: t(spec.advancement.why) });

  if (has('seeding')) {
    rows.push({ key: 'mode.sum.seeding', value: t(`rules.seeding.${rules.seeding}` as never) });
  }
  if (has('scoring')) {
    rows.push({
      key: 'mode.sum.points',
      value: t('mode.sum.pointsValue', { win: rules.winPoints, draw: rules.drawPoints, loss: rules.lossPoints }),
    });
  }
  if (has('reporting')) {
    // Points in a bracket: present, named, and explicitly powerless.
    rows.push({
      key: 'mode.sum.reporting',
      value: t('mode.sum.reportingValue', { win: rules.winPoints, draw: rules.drawPoints, loss: rules.lossPoints }),
    });
  }
  if (has('draws')) {
    if (spec.draws.policy === 'requires-resolution') {
      rows.push({
        key: 'mode.sum.drawRule',
        value: rules.allowDraws ? t(`mode.resolution.${resolution}` as never) : t('mode.draws.notAllowed'),
      });
    } else {
      rows.push({ key: 'mode.sum.draws', value: rules.allowDraws ? t('common.yes') : t('common.no') });
    }
  }
  if (has('tiebreak')) {
    const names = rules.tiebreakOrder.slice(0, 2)
      .map((k) => t(`rules.tiebreak.${k}` as never))
      .join(' \u2192 ');
    rows.push({ key: 'mode.sum.tiebreak', value: names || t('common.tbd') });
  }
  if (has('groups')) {
    const plan = groupPlan(rules, participantCount);
    rows.push({
      key: 'mode.sum.groupPlan',
      value: t('mode.sum.groupPlanValue', {
        sizes: plan.sizes.join(' / '), advance: rules.advancePerGroup ?? 2,
      }),
    });
  }
  if (has('rounds')) {
    rows.push({ key: 'mode.sum.rounds', value: t('mode.sum.roundsValue', { rounds: rules.swissRounds ?? 5 }) });
  }
  if (has('meeting')) {
    rows.push({ key: 'mode.sum.meeting', value: rules.homeAway ? t('preview.twice') : t('preview.once') });
  }
  if (has('byes')) {
    rows.push({ key: 'mode.sum.bye', value: t('mode.sum.byeValue', { points: rules.byePoints ?? 3 }) });
  }
  if (showsField(format, 'overtimeAllowed') && rules.overtimeAllowed) {
    rows.push({ key: 'mode.sum.overtime', value: t('common.yes') });
  }
  return rows;
}

/**
 * Glossary entries worth showing for a format - the terms that appear in this
 * mode's explanation or preview, and nowhere else. A league has no bracket, so
 * it is not offered the word.
 */
export function glossaryFor(format: string): (keyof Dict)[] {
  const mode = modeOf(format);
  const groups = visibleGroups(format);
  const terms: (keyof Dict)[] = ['mode.term.advancement'];
  if (mode.bracket) terms.push('mode.term.bracket', 'mode.term.bye');
  if (format === 'double-elimination') terms.push('mode.term.doubleElim', 'mode.term.draw');
  if (groups.includes('seeding')) terms.push('mode.term.seeding');
  if (groups.includes('tiebreak')) terms.push('mode.term.tiebreak');
  if (groups.includes('groups')) terms.push('mode.term.groupStage', 'mode.term.qualifier');
  if (format === 'league' || format === 'round-robin') terms.push('mode.term.matchday', 'mode.term.roundRobin');
  if (format === 'swiss') terms.push('mode.term.scoreGroup', 'mode.term.swiss');
  if (mode.settings.includes('reporting')) terms.push('mode.term.reportingOnly');
  return terms;
}
