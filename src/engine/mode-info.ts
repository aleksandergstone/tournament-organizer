export type PickerGroup = ModeInfo['group'];

export const PICKER_GROUPS: readonly PickerGroup[] = ['quick', 'ranking', 'groups', 'other'];

const GROUP_TITLES: Record<PickerGroup, keyof Dict> = {
  quick: 'mode.groupQuick',
  ranking: 'mode.groupRanking',
  groups: 'mode.groupGroups',
  other: 'mode.groupOther',
};

export function pickerGroupTitle(group: PickerGroup): keyof Dict {
  return GROUP_TITLES[group];
}

/** The modes for a picker group, in catalogue order. */
export function modesInGroup(group: PickerGroup): ModeInfo[] {
  return MODES.filter((m) => m.group === group);
}

// ---- the confirmation summary ----------------------------------------------

export interface SummaryLine { key: keyof Dict; value: string }

/**
 * The rules that actually apply, as short lines — the "before you create it"
 * block. Only visible groups produce a line, so a bracket never claims to score
 * points and a league never claims to have rounds.
 */
export function summaryRows(format: string, rules: RuleSet): SummaryLine[] {
  const rows: SummaryLine[] = [];
  const has = (g: SettingGroup) => visibleGroups(format).includes(g);
  const group = ALL_GROUPS.filter(has);

  if (has('seeding')) {
    rows.push({ key: 'mode.sum.seeding', value: t(`rules.seeding.${rules.seeding}` as never) });
  }
  if (has('scoring')) {
    rows.push({ key: 'mode.sum.points', value: t('mode.sum.pointsValue', { win: rules.winPoints, draw: rules.drawPoints, loss: rules.lossPoints }) });
    if (!rules.allowDraws) rows.push({ key: 'mode.sum.draws', value: t('common.no') });
  }
  if (rules.allowDraws && has('scoring') && !has('seeding')) {
    rows.push({ key: 'mode.sum.draws', value: t('common.yes') });
  }
  if (has('tiebreak')) {
    const names = rules.tiebreakOrder.slice(0, 2)
      .map((k) => t(`rules.tiebreak.${k}` as never))
      .join(' \u2192 ');
    rows.push({ key: 'mode.sum.tiebreak', value: names });
  }
  if (has('groups')) {
    rows.push({ key: 'mode.sum.groups', value: t('mode.sum.groupsValue', { groups: rules.groupCount ?? 2, advance: rules.advancePerGroup ?? 2 }) });
  }
  if (has('rounds')) {
    rows.push({ key: 'mode.sum.rounds', value: t('mode.sum.roundsValue', { rounds: rules.swissRounds ?? 5 }) });
  }
  if (has('meeting')) {
    rows.push({ key: 'mode.sum.meeting', value: rules.homeAway ? t('preview.twice') : t('preview.once') });
  }
  if (has('byes')) {
    rows.push({ key: 'mode.sum.bye', value: t('mode.sum.byeValue', { points: rules.byePoints ?? 3 }) });
  }
  if (has('seeding') && rules.overtimeAllowed) {
    rows.push({ key: 'mode.sum.overtime', value: t('common.yes') });
  }
  return rows;
}

/**
 * Glossary entries worth showing for a format - the terms that appear in this
 * mode's explanation or preview, and nowhere else. A league has no bracket, so
 * it is not offered the word.
 */
export function glossaryFor(format: string): (keyof Dict)[] {
  const mode = modeOf(format);
  const groups = visibleGroups(format);
  const terms: (keyof Dict)[] = [];
  if (mode.bracket) terms.push('mode.term.bracket', 'mode.term.bye');
  if (groups.includes('seeding')) terms.push('mode.term.seeding');
  if (groups.includes('tiebreak')) terms.push('mode.term.tiebreak');
  if (groups.includes('groups')) terms.push('mode.term.groupStage', 'mode.term.qualifier');
  if (format === 'league' || format === 'round-robin') terms.push('mode.term.matchday');
  if (format === 'swiss') terms.push('mode.term.scoreGroup');
  if (format === 'double-elimination') terms.push('mode.term.doubleElim');
  return terms;
}
