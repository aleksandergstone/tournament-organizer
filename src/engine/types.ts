/**
 * How a level match inside a bracket is settled. A draw cannot decide who
 * advances, so a format that allows draws has to say what happens next instead
 * of leaving the bracket stuck.
 *  - none:     draws are not allowed; the app refuses to record one
 *  - overtime: the extra time decides; record the result as overtime
 *  - replay:   the match is played again; the next round waits
 *  - penalty:  a shoot-out / decider decides
 *  - tiebreak: a seeded decider decides
 */
export type DrawResolution = 'none' | 'overtime' | 'replay' | 'penalty' | 'tiebreak';

/**
 * The stages a custom event can be built from. Only `pairings` is generated by
 * the app today; the rest exist so the organizer can say what they want, and the
 * validation names the ones that are not available instead of ignoring them.
 */
export const CUSTOM_STAGES = ['pairings', 'groups', 'bracket', 'swiss'] as const;
export type CustomStage = typeof CUSTOM_STAGES[number];
/** The only stage the generator can build; the rest are refused by validation. */
export const GENERATED_CUSTOM_STAGES: readonly CustomStage[] = ['pairings'];

export interface RuleSet {
  rounds?: number;            // swiss rounds, or null = auto
  matchLengthMin?: number | null;
  winPoints: number;
  drawPoints: number;
  lossPoints: number;
  allowDraws: boolean;
  /** Only consulted where a draw is allowed inside a bracket. */
  drawResolution?: DrawResolution;
  /**
   * The stage a custom event is built from. The organizer states it instead of
   * letting the app assume one; only `pairings` is generated today, and the
   * validation refuses the others by name.
   */
  customStage?: CustomStage;
  tiebreakOrder: TiebreakKey[];
  walkoverWinnerPoints: number; // default = winPoints
  overtimeAllowed: boolean;
  seeding: 'seeded' | 'random' | 'manual';
  groupCount?: number;        // for groups-knockout
  advancePerGroup?: number;   // top N advance
  homeAway?: boolean;         // league double round-robin
  swissRounds?: number;
  byePoints?: number;         // points for bye (odd numbers)
  /**
   * Points that win one period (a set, game or leg). 0/absent = the sport has no
   * periods and the match score is a running total (football, chess). Set by the
   * discipline layer and edited on the Rules screen.
   */
  periodPoints?: number;
  /** Periods needed to win the match (best-of is 2*periodsToWin-1). */
  periodsToWin?: number;
  /** A period must be won by two clear points (volleyball, table tennis). */
  winByTwo?: boolean;
  // Sailing-specific settings
  /** Number of scheduled races in the series */
  scheduledRaces?: number;
  /** Minimum races to constitute a valid series */
  minRacesForSeries?: number;
  /** Whether to use flights (fleet splitting) */
  useFlights?: boolean;
  /** Fleet assignment method */
  fleetAssignment?: 'random' | 'seeded' | 'qualifying';
  /** Time limit for first boat (minutes) */
  timeLimitFirstMin?: number;
  /** Time limit for subsequent boats (minutes) */
  timeLimitOthersMin?: number;
  /** Target time for first boat (minutes) */
  targetTimeMin?: number;
  /** Scoring system */
  scoringSystem?: 'low-point' | 'high-point' | 'bonus-point' | 'custom';
  /** Whether to use handicap */
  useHandicap?: boolean;
  /** Handicap system name */
  handicapSystem?: string;
  /** Discard profile */
  discardProfile?: {
    racesToQualify: number;
    schedule: [number, number][];
  };
  /** Custom points per finishing position (1-based) used when scoringSystem === 'custom'. */
  customPoints?: Record<number, number>;
  /**
   * Points awarded to a boat that did not finish a race (DNS/DNF/DSQ/OCS/RET…).
   * Absent = the RRS default: number of entered boats + 1 for low-point systems.
   */
  nonFinisherPoints?: number;
  /** Configurable tie-break order for a sailing series (engine supplies a default). */
  sailingTiebreak?: SailingTiebreakKey[];
  /** Medal race / final-race configuration for the series. */
  medalRace?: MedalRaceConfig;
}

export type TiebreakKey = 'points' | 'wins' | 'diff' | 'scored' | 'buchholz' | 'seed' | 'name';

/**
 * How equal net points are separated in a sailing series, in priority order.
 * The engine applies these in sequence; the first that separates two boats wins.
 */
export type SailingTiebreakKey =
  | 'net-points'      // fewest net points (low-point) / most (high-point) — always first
  | 'most-first'      // most 1st places
  | 'most-second'     // most 2nd places
  | 'most-third'      // most 3rd places
  | 'most-wins'       // most race wins (position 1)
  | 'last-race'       // better result in the last sailed race
  | 'fewest-discards' // fewest discarded points
  | 'manual';         // organiser decides (stable order)

